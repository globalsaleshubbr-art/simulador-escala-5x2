import asyncio, re, os
from playwright.async_api import async_playwright
import os
D=os.path.join(os.path.dirname(os.path.abspath(__file__)), "saida") + "/"
os.makedirs(D+"exp", exist_ok=True)
URL=os.environ.get("ESCALA_URL", "file://" + os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "dist", "simples-local.html"))
ok=[]; fail=[]
def check(n,c,i=""): (ok if c else fail).append(n+("" if c else f" [{i}]"))
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); ctx = await b.new_context(viewport={"width":1440,"height":1000}, accept_downloads=True); pg = await ctx.new_page()
        errs=[]; pg.on("pageerror", lambda e: errs.append(str(e)))
        async def go(h): await pg.evaluate(f"location.hash='{h}'"); await pg.wait_for_timeout(900)
        await pg.goto(URL); await pg.wait_for_timeout(3500)
        await go("ferias")
        check("tela de férias abre", "Controle de férias" in await pg.inner_text("h1"))
        check("formulário fixo na tela", await pg.is_visible("#vac-form"))
        await pg.select_option("#vac-f-sector", "Padaria"); await pg.wait_for_timeout(200)
        n = await pg.eval_on_selector("#vac-who", "s=>s.options.length")
        check("filtro de setor no formulário", n == 9, n)
        await pg.select_option("#vac-f-sector", "all"); await pg.wait_for_timeout(200)
        # sem admissão: só o mês programado
        check("sem campo de admissão", "Admissão" not in await pg.inner_text("#vac-table"))
        tela = await pg.inner_text("main")
        check("sem saldo/vencimento", all(t not in tela for t in ["Saldo", "Vence em", "Sem data de admissão", "Quitadas"]), [t for t in ["Saldo", "Vence em", "Sem data de admissão", "Quitadas"] if t in tela])
        # de … até no calendário: 4 pessoas (a lista reordena ao gravar: pega pelos ids)
        ids = await pg.eval_on_selector_all("#vac-table tr[data-pessoa]", "rs=>rs.slice(0,4).map(r=>r.dataset.pessoa)")
        for k, pid in enumerate(ids):
            await pg.fill(f"#vac-de-{pid}", f"2027-0{k+2}-01"); await pg.wait_for_timeout(300)
        check("só o início: fim pelos dias da loja (30)", await pg.input_value(f"#vac-ate-{ids[0]}") == "2027-03-02" and "30 dias" in await pg.inner_text(f"#vac-dias-{ids[0]}"), await pg.input_value(f"#vac-ate-{ids[0]}"))
        await pg.fill(f"#vac-ate-{ids[1]}", "2027-03-15"); await pg.wait_for_timeout(300)
        check("escolher o fim muda os dias", "15 dias" in await pg.inner_text(f"#vac-dias-{ids[1]}"))
        await pg.fill(f"#vac-de-{ids[1]}", "2027-03-05"); await pg.wait_for_timeout(300)
        check("mudar o início mantém a duração", await pg.input_value(f"#vac-ate-{ids[1]}") == "2027-03-19", await pg.input_value(f"#vac-ate-{ids[1]}"))
        meses = await pg.eval_on_selector_all("#vac-table input[id^='vac-de-']", "els=>els.map(e=>[e.id,e.value]).filter(x=>x[1])")
        check("4 pessoas com férias programadas", len(meses) == 4, meses)
        kp = await pg.inner_text("#vac-kpis")
        check("KPIs: com e sem férias programadas", re.search(r"COM FÉRIAS PROGRAMADAS\s+4", kp, re.I) is not None and "SEM FÉRIAS PROGRAMADAS" in kp.upper(), kp[:200])
        # programar férias pela primeira linha (Frente de Caixa)
        await pg.select_option("#vac-tbl-sector", "Frente de Caixa"); await pg.wait_for_timeout(300)
        await pg.locator("#vac-table tbody tr").first.get_by_role("button", name="Programar").click(); await pg.wait_for_timeout(300)
        await pg.fill("#vac-start", "2026-11-09"); await pg.fill("#vac-days", "20"); await pg.wait_for_timeout(300)
        prev = await pg.inner_text("#vac-preview")
        check("prévia mostra período e cobertura", "20 dias" in prev and "Cobertura" in prev, prev[:300])
        if await pg.locator("#vac-ok").count(): await pg.check("#vac-ok")
        await pg.click("#vac-save"); await pg.wait_for_timeout(500)
        bars = await pg.locator("#vac-map button[aria-label*='Alterar']").count()
        check("barra no mapa de férias", bars == 1, bars)
        check("formulário continua na tela depois de lançar", await pg.is_visible("#vac-form"))
        await pg.locator("#vac-table tbody tr").first.get_by_role("button", name="Programar").click(); await pg.wait_for_timeout(300)
        await pg.fill("#vac-start", "2026-11-12"); await pg.wait_for_timeout(200)
        check("avisa férias já lançadas no período", await pg.is_visible("#vac-edit-overlap"))
        await pg.click("#vac-edit-overlap"); await pg.wait_for_timeout(200)
        check("passa a alterar as férias existentes", "Alterar férias" in await pg.inner_text("#vac-form"))
        await pg.get_by_role("button", name="Programar outras férias").click(); await pg.wait_for_timeout(200)
        await pg.select_option("#vac-tbl-sector", "all"); await pg.wait_for_timeout(200)
        # segunda pessoa, 5 dias (curto) e limite de 1 no setor
        await pg.fill("#vr-sim", "1"); await pg.wait_for_timeout(200)
        await pg.click("#vac-new"); await pg.wait_for_timeout(200)
        await pg.select_option("#vac-f-sector", "Frente de Caixa"); await pg.wait_for_timeout(200)
        opts = await pg.eval_on_selector("#vac-who", "s=>[...s.options].map(o=>o.value)")
        for o in opts:
            await pg.select_option("#vac-who", o); await pg.fill("#vac-start", "2026-11-15"); await pg.fill("#vac-days", "4"); await pg.wait_for_timeout(250)
            prev = await pg.inner_text("#vac-preview")
            if "ao mesmo tempo" in prev: break
        check("aviso de limite do setor", "ao mesmo tempo" in prev, prev[:400])
        check("aviso de parte curta", "mínimo da loja" in prev, prev[:400])
        await pg.click("#vac-save"); await pg.wait_for_timeout(500)
        n_all = await pg.locator("#vac-map button[aria-label*='Alterar']").count()
        await pg.select_option("#vac-map-sector", "Padaria"); await pg.wait_for_timeout(300)
        n_pad = await pg.locator("#vac-map button[aria-label*='Alterar']").count()
        await pg.select_option("#vac-map-sector", "Frente de Caixa"); await pg.wait_for_timeout(300)
        n_fc = await pg.locator("#vac-map button[aria-label*='Alterar']").count()
        check("filtro de setor no mapa", n_all == 2 and n_pad == 0 and n_fc == 2, (n_all, n_pad, n_fc))
        await pg.locator("#vac-map").screenshot(path=D+"vac_map.png")
        await pg.select_option("#vac-map-sector", "all")
        al = await pg.inner_text("#vac-alerts")
        check("alertas listados", "ao mesmo tempo" in al, al[:200])
        await pg.screenshot(path=D+"ferias_full.png", full_page=True)
        # aparece na escala (semana de 09/11)
        await go("escala")
        await pg.fill("#sem-date", "2026-11-10"); await pg.wait_for_timeout(500)
        sem = await pg.inner_text("#semana")
        check("férias aparecem na Semana", "Férias" in sem)
        # editar e remover pelo mapa
        await go("ferias")
        await pg.locator("#vac-map button[aria-label*='Alterar']").first.click(); await pg.wait_for_timeout(300)
        await pg.get_by_role("button", name="Remover estas férias").click(); await pg.get_by_role("button", name="Confirmar remoção").click(); await pg.wait_for_timeout(400)
        bars = await pg.locator("#vac-map button[aria-label*='Alterar']").count()
        check("remover férias pelo mapa", bars == 1, bars)
        # filtros
        await pg.select_option("#vac-status", "semMes"); await pg.wait_for_timeout(300)
        n = await pg.locator("#vac-table tbody tr").count()
        check("filtro de situação (sem mês)", n == 56, n)
        await pg.select_option("#vac-status", "comMes"); await pg.wait_for_timeout(300)
        check("filtro de situação (com mês)", await pg.locator("#vac-table tbody tr").count() == 4)
        await pg.select_option("#vac-status", "all")
        await pg.select_option("#vac-sector", "Padaria"); await pg.wait_for_timeout(300)
        n2 = await pg.locator("#vac-table tbody tr").count()
        check("filtro de setor", n2 == 9, n2)
        await pg.select_option("#vac-sector", "all"); await pg.wait_for_timeout(200)
        await pg.select_option("#vac-tbl-sector", "Açougue"); await pg.wait_for_timeout(300)
        n3 = await pg.locator("#vac-table tbody tr").count()
        sub = await pg.locator("#vac-table tbody tr td:first-child span.block").all_inner_texts()
        check("filtro de setor na tabela", n3 == 9 and all("Açougue" in x for x in sub), (n3, sub[:2]))
        await pg.select_option("#vac-tbl-sector", "all")
        async with pg.expect_download(timeout=60000) as dl: await pg.get_by_role("button", name="Baixar (Excel)").click()
        d = await dl.value; f = D+"exp/"+d.suggested_filename; await d.save_as(f)
        check("Excel de férias", os.path.getsize(f) > 4000)
        # persistência
        await pg.reload(); await pg.wait_for_timeout(3500); await go("ferias")
        v = await pg.eval_on_selector_all("#vac-table input[id^='vac-de-']", "els=>els.map(e=>[e.id,e.value]).filter(x=>x[1])")
        check("férias programadas salvas após recarregar", sorted(v) == sorted(meses), (v, meses))
        # programadas aparecem tracejadas no mapa (no ano delas)
        anos = sorted({m[1][:4] for m in meses})
        cur = await pg.inner_text("#vac-year")
        while cur < anos[-1]:
            await pg.get_by_role("button", name="Próximo ano").click(); await pg.wait_for_timeout(250); cur = await pg.inner_text("#vac-year")
        check("programadas tracejadas no mapa", await pg.locator("#vac-map button[data-plano]").count() >= 1)
        dp = await pg.locator("#vac-map button[data-plano]").first.get_attribute("data-plano")
        await pg.locator("#vac-map button[data-plano]").first.click(); await pg.wait_for_timeout(300)
        st = await pg.input_value("#vac-start")
        check("clicar no tracejado abre o formulário com o período programado", st == dp, (st, dp))
        # escolha automática para quem não tem mês
        await pg.select_option("#vac-store", "all") if await pg.locator("#vac-store").count() else None
        await pg.locator("#vac-auto button").click(); await pg.wait_for_timeout(200)
        await pg.locator("#vac-auto button").filter(has_text="Escolher para").click(); await pg.wait_for_timeout(1200)
        toast = await pg.inner_text("body")
        check("escolha automática avisa", "Férias programadas para" in toast)
        vals = await pg.eval_on_selector_all("#vac-table tr[data-pessoa]", "rs=>rs.map(r=>[(r.querySelector('td span.block')||{}).textContent||'', ((r.querySelector('input[id^=vac-de-]')||{}).value||'').slice(0,7)])")
        sem = [x for x in vals if not x[1]]
        check("quase todos com férias programadas (exceto quem tem férias lançadas)", len(sem) <= 2, len(sem))
        from collections import Counter
        por = {}
        for sub, m in vals:
            if m: por.setdefault(sub.split(" · ")[0], Counter())[m] += 1
        espalha = all(max(c.values()) - min(c.values()) <= 2 for c in por.values() if len(c) >= 6)
        check("cada setor espalhado pelos meses", espalha and len(por) >= 3, {k: dict(v) for k, v in list(por.items())[:2]})
        kp = await pg.inner_text("#vac-kpis")
        check("regras sem aviso de vencimento nem desconto por faltas", await pg.locator("#vr-aviso").count() == 0 and await pg.locator("#vr-faltas").count() == 0)
        await pg.set_viewport_size({"width":390,"height":844}); await pg.wait_for_timeout(300)
        sw = await pg.evaluate("document.documentElement.scrollWidth")
        check("celular sem rolagem lateral", sw <= 392, sw)
        check("sem erros JS", not errs, errs[:2])
        await b.close()
    print("OK", len(ok)); [print(" ✓",x) for x in ok]; print("FALHAS", len(fail)); [print(" ✗",x) for x in fail]
asyncio.run(main())
import sys as _s
_s.exit(1 if fail else 0)
